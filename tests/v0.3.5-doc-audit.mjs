import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const here = path.dirname(fileURLToPath(import.meta.url));
const root = process.env.JANUS_TEST_ROOT ? path.resolve(process.env.JANUS_TEST_ROOT) : path.resolve(here, '..');
const read = (p) => fs.readFileSync(path.join(root,p),'utf8');
const assert = (ok,msg) => { if(!ok) throw new Error(msg); };
const readme = read('README.md');
const changelog = read('CHANGELOG.md');
const version = read('VERSION.txt');
const html = read('index.html');
const gate = read('tests/V0_3_5_RELEASE_GATE.md');
const gate2 = read('tests/V0_3_2_RELEASE_GATE.md');
const gate3 = read('tests/V0_3_3_RELEASE_GATE.md');
const gate4 = read('tests/V0_3_4_RELEASE_GATE.md');
const hashes = JSON.parse(read('docs/EXPECTED_CONTRACT_HASHES.json'));
assert(readme.includes('# JANUS Governance Challenge Harness v0.3.5'), 'README current version missing.');
assert(readme.includes('unsigned client-side artifact'), 'README unsigned-client disclosure missing.');
assert(readme.includes('controls the page/DevTools'), 'README DevTools limitation missing.');
assert(readme.includes('accidental or uncoordinated later mutation'), 'README snapshot limitation missing.');
assert(!readme.includes('It is tamper-proof after export'), 'README contains a tamper-proof integrity overclaim.');
assert(readme.includes('tests/v0.3.5-regression.mjs'), 'README current behavioral suite missing.');
assert(readme.includes('tests/v0.3.5-doc-audit.mjs'), 'README current doc suite missing.');
assert(readme.includes('tests/v0.3.5-mutation-regression.mjs'), 'README current mutation suite missing.');
assert(readme.includes('V0_3_5_RELEASE_GATE.md'), 'README current gate missing.');
assert(!readme.includes('automated local regression coverage is included under `tests/v0.3.2-regression.mjs`'), 'README retains stale v0.3.2 current-suite claim.');
assert(!readme.includes('Version 1.0 itself must then be deployed'), 'README retains orphaned Version 1.0 sentence.');
assert(html.includes('v0.3.5'), 'UI version not v0.3.5.');
assert(html.includes('Evidence exports are unsigned client-side artifacts'), 'UI integrity-limit disclosure missing.');
assert(html.includes('DevTools/console'), 'UI DevTools/console limitation missing.');
assert(changelog.trimStart().startsWith('# Changelog'), 'CHANGELOG title is not first.');
assert(changelog.indexOf('## v0.3.5') > changelog.indexOf('# Changelog'), 'v0.3.5 entry missing or misplaced.');
assert(!changelog.includes('remaining V031-NEW-07 observability gap'), 'CHANGELOG retains incorrect V031-NEW-07 history.');
assert(changelog.includes('V031-NEW-07 observability was confirmed closed'), 'CHANGELOG lacks corrected V031-NEW-07 history.');
assert(version.includes('Version 0.3.5'), 'VERSION current version missing.');
assert(version.includes('canonical duplicate comparison'), 'VERSION v0.3.5 correction missing.');
assert(version.includes('Independent closure: pending'), 'VERSION overclaims closure.');
for (const [name,text] of [['v0.3.2',gate2],['v0.3.3',gate3],['v0.3.4',gate4]]) assert(text.startsWith('# SUPERSEDED'), `${name} gate is not marked superseded.`);
assert(gate.includes('v0.3.5-regression.mjs'), 'v0.3.5 gate missing behavioral suite.');
assert(gate.includes('v0.3.5-doc-audit.mjs'), 'v0.3.5 gate missing documentation audit.');
assert(gate.includes('v0.3.5-mutation-regression.mjs'), 'v0.3.5 gate missing mutation suite.');
assert(!gate.includes('v0.3.2-regression.mjs'), 'v0.3.5 gate incorrectly requires retired suite.');
assert(hashes.version === '0.3.5', 'Expected contract hash file version mismatch.');
assert(Array.isArray(hashes.scenarios) && hashes.scenarios.length === 6, 'Expected contract hash file must contain six scenarios.');
console.log('JANUS v0.3.5 documentation/release audit: PASS');
